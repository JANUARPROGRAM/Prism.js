#!/usr/bin/env node
/**
 * Regenerates the sample models in assets/models/ (crate.obj/.mtl/.png, house.obj/.mtl).
 * Dependency-free: the PNG is encoded with node:zlib.   node scripts/make-sample-assets.js
 */
import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const outDir = join(fileURLToPath(new URL('..', import.meta.url)), 'assets', 'models');
mkdirSync(outDir, { recursive: true });

// ---------- minimal PNG writer ----------
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
	let c = n;
	for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
	return c >>> 0;
});
function crc32(buf) {
	let c = 0xffffffff;
	for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 255] ^ (c >>> 8);
	return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
	const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
	const length = Buffer.alloc(4); length.writeUInt32BE(data.length);
	const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body));
	return Buffer.concat([length, body, crc]);
}
function encodePNG(width, height, rgba) {
	const header = Buffer.alloc(13);
	header.writeUInt32BE(width, 0); header.writeUInt32BE(height, 4);
	header[8] = 8; header[9] = 6; // 8-bit RGBA
	const rows = Buffer.alloc((width * 4 + 1) * height);
	for (let y = 0; y < height; y++) {
		rows[y * (width * 4 + 1)] = 0; // filter: none
		rgba.copy(rows, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
	}
	return Buffer.concat([
		Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
		chunk('IHDR', header), chunk('IDAT', deflateSync(rows)), chunk('IEND', Buffer.alloc(0))
	]);
}

// ---------- crate texture: planks, dark frame, an 8x8 solid "knot" around the center ----------
const SIZE = 64;
const rgba = Buffer.alloc(SIZE * SIZE * 4);
const KNOT = [205, 140, 75];
for (let y = 0; y < SIZE; y++) {
	for (let x = 0; x < SIZE; x++) {
		let color;
		const inKnot = x >= 28 && x < 36 && y >= 28 && y < 36;
		if (inKnot) color = KNOT;
		else if (x < 6 || y < 6 || x >= SIZE - 6 || y >= SIZE - 6) color = [88, 56, 28];
		else if ([19, 20, 39, 40].includes(y)) color = [120, 78, 44];
		else {
			const grain = ((Math.sin(x * 2.3 + Math.floor(y / 20) * 5.1) + 1) * 3.5) | 0; // deterministic 0..7
			color = [170 + grain, 118 + grain, 68 + grain];
		}
		rgba.set([...color, 255], (y * SIZE + x) * 4);
	}
}
writeFileSync(join(outDir, 'crate.png'), encodePNG(SIZE, SIZE, rgba));

// ---------- OBJ helpers ----------
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const fmt = (n) => String(+n.toFixed(5));

/** Crate: 8 shared positions, 4 uvs, 6 normals; faces are quads written as v/vt/vn. */
function crateObj() {
	const faces = [
		{ n: [1, 0, 0], u: [0, 0, -1], v: [0, 1, 0] }, { n: [-1, 0, 0], u: [0, 0, 1], v: [0, 1, 0] },
		{ n: [0, 1, 0], u: [1, 0, 0], v: [0, 0, -1] }, { n: [0, -1, 0], u: [1, 0, 0], v: [0, 0, 1] },
		{ n: [0, 0, 1], u: [1, 0, 0], v: [0, 1, 0] }, { n: [0, 0, -1], u: [-1, 0, 0], v: [0, 1, 0] }
	];
	const positions = new Map();
	const lines = ['# Sample crate for Vertex (generated by scripts/make-sample-assets.js)', 'mtllib crate.mtl', 'o Crate'];
	const faceLines = [];
	const corners = [[0, 0], [1, 0], [1, 1], [0, 1]];
	faces.forEach((f, fi) => {
		const refs = corners.map(([s, t], ci) => {
			const p = f.n.map((n, k) => n * 0.5 + f.u[k] * (s - 0.5) + f.v[k] * (t - 0.5));
			const key = p.map(fmt).join(' ');
			if (!positions.has(key)) positions.set(key, positions.size + 1);
			return `${positions.get(key)}/${ci + 1}/${fi + 1}`;
		});
		faceLines.push(`f ${refs.join(' ')}`);
	});
	for (const key of positions.keys()) lines.push(`v ${key}`);
	lines.push('vt 0 0', 'vt 1 0', 'vt 1 1', 'vt 0 1');
	for (const f of faces) lines.push(`vn ${f.n.join(' ')}`);
	lines.push('usemtl Wood', 's off', ...faceLines);
	return lines.join('\n') + '\n';
}

/** House: walls (quads), roof (quads + triangles) and a door; all faces as v//vn, three materials. */
function houseObj() {
	const vertices = [], normals = [], out = [];
	const vertex = (p) => { vertices.push(`v ${p.map(fmt).join(' ')}`); return vertices.length; };
	const normalOf = (a, b, c) => {
		const n = cross(b.map((v, i) => v - a[i]), c.map((v, i) => v - a[i]));
		const l = Math.hypot(...n);
		return n.map((v) => v / l);
	};
	const poly = (points) => {
		const n = normalOf(points[0], points[1], points[2]);
		normals.push(`vn ${n.map(fmt).join(' ')}`);
		return `f ${points.map((p) => `${vertex(p)}//${normals.length}`).join(' ')}`;
	};
	const [w, d, h, r] = [1.2, 0.9, 1.1, 1.8]; // half width, half depth, wall height, ridge height
	const A = [-w, 0, d], B = [w, 0, d], C = [w, h, d], D = [-w, h, d];
	const E = [-w, 0, -d], F = [w, 0, -d], G = [w, h, -d], H = [-w, h, -d];
	const R1 = [0, r, d], R2 = [0, r, -d];
	out.push('o Walls', 'usemtl Walls',
		poly([A, B, C, D]), poly([F, E, H, G]), poly([B, F, G, C]), poly([E, A, D, H]), poly([E, F, B, A]));
	out.push('o Roof', 'usemtl Roof',
		poly([D, C, R1]), poly([G, H, R2]), poly([C, G, R2, R1]), poly([H, D, R1, R2]));
	const z = d + 0.01;
	out.push('o Door', 'usemtl Door', poly([[-0.25, 0, z], [0.25, 0, z], [0.25, 0.75, z], [-0.25, 0.75, z]]));
	return ['# Sample house for Vertex (generated by scripts/make-sample-assets.js)', 'mtllib house.mtl', ...vertices, ...normals, ...out].join('\n') + '\n';
}

writeFileSync(join(outDir, 'crate.obj'), crateObj());
writeFileSync(join(outDir, 'crate.mtl'), 'newmtl Wood\nKa 1 1 1\nKd 1 1 1\nKs 0 0 0\nmap_Kd crate.png\n');
writeFileSync(join(outDir, 'house.obj'), houseObj());
writeFileSync(join(outDir, 'house.mtl'), [
	'newmtl Walls', 'Kd 0.85 0.75 0.55', '',
	'newmtl Roof', 'Kd 0.70 0.15 0.10', '',
	'newmtl Door', 'Kd 0.35 0.20 0.10', ''
].join('\n'));
console.log('Wrote assets/models/: crate.obj crate.mtl crate.png house.obj house.mtl');
